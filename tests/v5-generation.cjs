const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const read = p => fs.readFileSync(p, 'utf8');

const engine = read('src/v5-engine.js');
const treatments = Array.from({ length: 20 }, (_, n) => ({ captionLabel: `Caption ${n}`, transitionLabel: `Transition ${n}`, motionLabel: `Motion ${n}`, captionMode: n, transitionMode: n, motionMode: n }));
const directions = Array.from({ length: 20 }, (_, n) => [`direction ${n}`, 'description', `layout-${n}`]);
const context = vm.createContext({ DIRECTED_TREATMENTS: treatments, DIRECTED_DIRECTIONS: directions, Math });
vm.runInContext(engine, context);
const base = { id: 'original', index: 6, captionLabel: 'base', transitionLabel: 'base', motionLabel: 'base' };
assert.equal(vm.runInContext('V5_VARIATION', context), 0);
assert.equal(vm.runInContext('v5SceneDirection', context)(base, 4), base);
vm.runInContext('V5_VARIATION=1', context);
const generated = vm.runInContext('v5SceneDirection', context);
const cut1 = Array.from({ length: 22 }, (_, i) => generated(base, i));
const repeated = Array.from({ length: 22 }, (_, i) => generated(base, i));
assert.deepEqual(cut1, repeated, 'Same generation must render identical frames');
assert.ok(new Set(cut1.map(d => `${d.captionMode}:${d.motionMode}:${d.transitionMode}:${d.layout}`)).size > 16, 'Scenes need diverse motion grammar');
vm.runInContext('V5_VARIATION=2', context);
assert.notDeepEqual(cut1, Array.from({ length: 22 }, (_, i) => generated(base, i)), 'Generate should create a new direction');
assert.match(read('index.html'), /id="rail-add"/);
assert.match(read('index.html'), /id="generate-btn"/);
assert.match(read('styles/v5.css'), /border-radius:35px/);
assert.doesNotMatch(read('src/assets.js'), /photos\[i%photos\.length\]/, 'Unrelated images cannot be spread across scenes');
assert.doesNotMatch(read('src/assets.js'), /generic\[i%generic\.length\]/, 'Unrelated videos cannot be spread across scenes');
assert.match(read('src/assets.js'), /\(\?:first\|second\)/, 'ClipFlow first/second reference frames should stay reference media');
assert.match(read('src/directed.js'), /v5Clipflow/);
console.log('PASS: V5 generation deterministic and unique, no generic asset scattering, consistent frames and controls.');
